/* ====================================================================
   SCRIPT: 1_star_create_schema.sql
   PURPOSE: Initializes the Presentation Layer.
            This schema is strictly client-facing and designed for BI 
            tools and rapid querying.
   ARCHITECTURAL NOTE: This fact table targets `dw.live_15m_agg`. It 
            deliberately avoids synthetic/imputed data generated by
	    forward filling.
   ==================================================================== */

CREATE SCHEMA IF NOT EXISTS star;

-- 1. DIMENSION: SYMBOL
CREATE TABLE star.dim_symbol (
    symbol_key SERIAL PRIMARY KEY,
    symbol text UNIQUE NOT NULL,
    asset_type text, company_name text, sector text, industry text, exchange text,
    is_active boolean DEFAULT true
);

-- 2. DIMENSION: DATE
CREATE TABLE star.dim_date (
    date_key integer PRIMARY KEY, 
    full_date date UNIQUE NOT NULL,
    year smallint, quarter smallint, month smallint, day_of_week smallint,
    day_name text, is_trading_day boolean, holiday_flag boolean, pre_holiday boolean, post_holiday boolean
);

-- 3. DIMENSION: TIMESLOT
CREATE TABLE star.dim_timeslot (
    time_slot_key integer PRIMARY KEY, 
    hour smallint, minute smallint,
    slot_label text, session_type text, is_market_open boolean
);

-- 4. FACT: MARKET DATA 15M
-- NOTE: Uses a composite primary key (date, time, symbol) to guarantee
-- absolute idempotency. Contains raw `slot_count` and `status` to provide
-- clients with transparency into the raw tick density of each window.
CREATE TABLE star.fact_market_data_15m (
    date_key integer REFERENCES star.dim_date(date_key),
    time_slot_key integer REFERENCES star.dim_timeslot(time_slot_key),
    symbol_key integer REFERENCES star.dim_symbol(symbol_key),

    open numeric(18,6), high numeric(18,6), low numeric(18,6), close numeric(18,6), volume bigint,
    slot_count smallint, status text,

    lag_close_1 numeric(18,6), lag_close_5 numeric(18,6), lag_close_10 numeric(18,6),
    sma_close_5 numeric(18,6), sma_close_10 numeric(18,6), sma_close_20 numeric(18,6), sma_volume_5 numeric(18,6),
    close_diff_1 numeric(18,6), close_diff_5 numeric(18,6), pct_change_1 numeric(18,6), pct_change_5 numeric(18,6), log_return_1 numeric(18,6),
    day_monday smallint, day_tuesday smallint, day_wednesday smallint, day_thursday smallint, day_friday smallint,
    quarter_1 smallint, quarter_2 smallint, quarter_3 smallint, quarter_4 smallint,
    hour_early_morning smallint, hour_mid_morning smallint, hour_afternoon smallint, hour_late_afternoon smallint,
    previous_close numeric(18,6), overnight_gap_pct numeric(18,6), overnight_log_return numeric(18,6), is_gap_up smallint, is_gap_down smallint,

    created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (date_key, time_slot_key, symbol_key)
);
